FALLBACK = "pin"


def resolve(name=None, stored=None):
    """Ключ иконки по имени категории; stored — то, что лежит в Category.icon
    (исторически эмодзи, но может быть и ключ латиницей)."""
    if name and name.strip() in BY_NAME:
        return BY_NAME[name.strip()]
    if stored and stored.strip() in PATHS:
        return stored.strip()
    return FALLBACK


# Категории, для которых лежит готовая картинка в site_app/static/icons.
# Их рисовал гид — они и идут на сайт; PATHS ниже остаются запасным вариантом
# для служебных категорий и для всего, чему картинку ещё не сделали.
RASTER = {
    "waterfall", "viewpoint", "cave", "canyon", "mountain", "river",
    "reserve", "rock", "thermal", "dolmen", "temple", "village",
    "museum", "digs", "hiking", "horse", "jeep", "raft",
}


def render(key, css_class="cat-icon"):
    """Готовая разметка одной иконки. Экранировать на выходе не нужно и нельзя —
    в шаблоне подставляется через | safe."""
    cls = escape(css_class, quote=True)
    if key in RASTER:
        return f'<img class="{cls}" src="/assets/icons/{key}.png" alt="" aria-hidden="true">'
    body = PATHS.get(key) or PATHS[FALLBACK]
    return (
        f'<svg class="{cls}" viewBox="0 0 24 24" '
        f'fill="none" stroke="{OUT}" stroke-width="1.5" stroke-linecap="round" '
        'stroke-linejoin="round" aria-hidden="true">'
        f"{body}</svg>"
    )


def category_svg(name=None, stored=None, css_class="cat-icon"):
    """Короткий путь для роутера: имя категории → готовый <svg>."""
    return render(resolve(name, stored), css_class)
