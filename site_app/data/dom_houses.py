def _service(
    sid: str,
    title: str,
    teaser: str,
    price: str,
    unit: str,
    duration: str,
    includes: list[str],
    about: str,
    photo: str | None = None,
    photo_dict: dict | None = None,
) -> dict:
    shot = photo_dict or next((item for item in _GALLERY if photo and item["src"].endswith(f"/{photo}-960.webp")), None)
    return {
        "id": sid,
        "title": title,
        "teaser": teaser,
        "price": price,
        "unit": unit,
        "duration": duration,
        "includes": includes,
        "about": about,
        "photo": shot,
    }


def _q(question: str, answer: str, wifi: bool = False) -> dict:
    item = {"q": question, "a": answer}
    if wifi:
        item["network"] = "Aframe-demo"
        item["password"] = "les-demo"
    return item


