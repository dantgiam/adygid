LEAD_CHANNELS = [
    ("max", "Сообщение в MAX"),
    ("telegram", "Сообщение в Telegram"),
    ("call", "Звонок"),
    ("whatsapp", "WhatsApp"),
    ("email", "Почта"),
]
LEAD_CHANNEL_TITLES = dict(LEAD_CHANNELS)


def valid_pair(category: str | None, sub: str | None) -> bool:
    if category not in CATEGORY_BY_CODE:
        return False
    return not sub or (category, sub) in SUB_TITLES


def category_title(code: str | None) -> str:
    cat = CATEGORY_BY_CODE.get(code or "")
    return cat["title"] if cat else "—"


def sub_title(category: str | None, sub: str | None) -> str:
    return SUB_TITLES.get((category or "", sub or ""), "")


def as_json() -> list[dict]:
    """Для data-атрибута анкеты: выбор подкатегории зависит от категории."""
    return [
        {"code": c["code"], "title": c["title"], "subs": [{"code": s, "title": t} for s, t in c["subs"]]}
        for c in CATEGORIES
    ]
